// Repository names recorded in the generated header.
const (
	RepoAWS   = "hashicorp/terraform-provider-aws"
	RepoAWSCC = "hashicorp/terraform-provider-awscc"
)

// DefaultDir returns the default checkout of repo under home: ~/src/github/_reference/<repo>.
func DefaultDir(home, repo string) string {
	return filepath.Join(home, "src", "github", "_reference", filepath.FromSlash(repo))
}

// Output is what [Generate] writes: the YAML and the license that goes next to it.
type Output struct {
	YAML    []byte
	License []byte
}

// ErrSource is returned when a provider checkout doesn't have the expected layout.
var ErrSource = errors.New("unexpected provider source")

// Generate reads the aws and awscc provider checkouts and renders the generated typemap. The
// output depends only on the files in the checkouts, never on their paths.
func Generate(awsDir, awsccDir string) (*Output, error) {
	awsSrc, err := source(awsDir, RepoAWS)
	if err != nil {
		return nil, err
	}
	ccSrc, err := source(awsccDir, RepoAWSCC)
	if err != nil {
		return nil, err
	}
	attrs, err := attrConsts(filepath.Join(awsDir, "names", "attr_consts_gen.go"))
	if err != nil {
		return nil, err
	}
	resources, err := resources(filepath.Join(awsDir, "internal", "service"), attrs)
	if err != nil {
		return nil, err
	}
	tagris, err := tagTypes(filepath.Join(awsDir, "internal", "tags", "tagpolicy", "tagris-terraform-mapping.hcl"))
	if err != nil {
		return nil, err
	}
	cfn, err := cfnTypes(filepath.Join(awsccDir, "internal", "provider", "all_schemas.hcl"))
	if err != nil {
		return nil, err
	}
	for i := range resources {
		r := &resources[i]
		r.RE = tagris[r.TF]
		r.CFN = guessCFN(r, cfn)
	}
	gen := typemap.Generated{
		Sources:   []typemap.Source{awsSrc, ccSrc},
		Resources: resources,
		CFNTypes:  slices.Sorted(maps.Values(cfn)),
	}
	var body bytes.Buffer
	enc := yaml.NewEncoder(&body)
	enc.SetIndent(2) //nolint:mnd // two-space YAML indent
	if err = enc.Encode(gen); err != nil {
		return nil, fmt.Errorf("render typemap: %w", err)
	}
	if err = enc.Close(); err != nil {
		return nil, fmt.Errorf("render typemap: %w", err)
	}
	var b bytes.Buffer
	b.WriteString("# Code generated by `mise run typemap:gen`. DO NOT EDIT.\n")
	for _, s := range gen.Sources {
		fmt.Fprintf(&b, "# %s %s at %s\n", s.Repo, s.Version, s.Commit)
	}
	b.WriteString("# Derived from MPL-2.0 sources; see generated.yaml.LICENSE.\n")
	b.Write(body.Bytes())
	license, err := licenseFile(awsDir, awsccDir, awsSrc, ccSrc)
	if err != nil {
		return nil, err
	}
	return &Output{YAML: b.Bytes(), License: license}, nil
}

func source(dir, repo string) (typemap.Source, error) {
	v, err := os.ReadFile(filepath.Join(dir, "version", "VERSION"))
	if err != nil {
		return typemap.Source{}, fmt.Errorf("%w: %s: read version: %w", ErrSource, repo, err)
	}
	commit, err := headCommit(filepath.Join(dir, ".git"))
	if err != nil {
		return typemap.Source{}, fmt.Errorf("%w: %s: %w", ErrSource, repo, err)
	}
	return typemap.Source{Repo: repo, Version: strings.TrimSpace(string(v)), Commit: commit}, nil
}

// headCommit resolves HEAD without running git: a detached hash, a loose ref or packed-refs.
func headCommit(gitDir string) (string, error) {
	if fi, err := os.Stat(gitDir); err == nil && !fi.IsDir() {
		// A worktree or submodule: .git is a file that names the real directory.
		b, readErr := os.ReadFile(gitDir)
		if readErr != nil {
			return "", fmt.Errorf("read %s: %w", gitDir, readErr)
		}
		target := strings.TrimSpace(strings.TrimPrefix(string(b), "gitdir:"))
		if !filepath.IsAbs(target) {
			target = filepath.Join(filepath.Dir(gitDir), target)
		}
		gitDir = target
	}
	head, err := os.ReadFile(filepath.Join(gitDir, "HEAD")) //nolint:gosec // the checkout the operator named
	if err != nil {
		return "", fmt.Errorf("read HEAD: %w", err)
	}
	ref, ok := strings.CutPrefix(strings.TrimSpace(string(head)), "ref: ")
	if !ok {
		return strings.TrimSpace(string(head)), nil
	}
	//nolint:gosec // a ref inside the checkout the operator named
	if b, readErr := os.ReadFile(filepath.Join(gitDir, filepath.FromSlash(ref))); readErr == nil {
		return strings.TrimSpace(string(b)), nil
	}
	packed, err := os.ReadFile(filepath.Join(gitDir, "packed-refs")) //nolint:gosec // the checkout the operator named
	if err != nil {
		return "", fmt.Errorf("resolve %s: %w", ref, err)
	}
	for line := range strings.Lines(string(packed)) {
		if hash, name, found := strings.Cut(strings.TrimSpace(line), " "); found && name == ref {
			return hash, nil
		}
	}
	return "", fmt.Errorf("resolve %s: not in packed-refs", ref)
}

// attrConsts reads the names.AttrX string constants.
func attrConsts(path string) (map[string]string, error) {
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.SkipObjectResolution)
	if err != nil {
		return nil, fmt.Errorf("%w: parse %s: %w", ErrSource, filepath.Base(path), err)
	}
	out := map[string]string{}
	for _, decl := range f.Decls {
		if gd, isGen := decl.(*ast.GenDecl); isGen && gd.Tok == token.CONST {
			for _, spec := range gd.Specs {
				addConsts(out, spec)
			}
		}
	}
	return out, nil
}

func addConsts(out map[string]string, spec ast.Spec) {
	vs, ok := spec.(*ast.ValueSpec)
	if !ok {
		return
	}
	for i, name := range vs.Names {
		if i >= len(vs.Values) {
			continue
		}
		if v, isString := stringLit(vs.Values[i]); isString {
			out["names."+name.Name] = v
		}
	}
}

func stringLit(e ast.Expr) (string, bool) {
	lit, ok := e.(*ast.BasicLit)
	if !ok || lit.Kind != token.STRING {
		return "", false
	}
	s, err := strconv.Unquote(lit.Value)
	return s, err == nil
}

// resources reads every service_package_gen.go under dir.
func resources(dir string, attrs map[string]string) ([]typemap.GenResource, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("%w: %w", ErrSource, err)
	}
	byTF := map[string]typemap.GenResource{}
	for _, e := range entries {
		path := filepath.Join(dir, e.Name(), "service_package_gen.go")
		if !e.IsDir() {
			continue
		}
		if _, statErr := os.Stat(path); statErr != nil {
			continue
		}
		found, parseErr := servicePackage(path, e.Name(), attrs)
		if parseErr != nil {
			return nil, parseErr
		}
		required, listErr := listRequired(filepath.Join(dir, e.Name()), attrs)
		if listErr != nil {
			return nil, listErr
		}
		for _, r := range found {
			merge(byTF, r, required[r.TF])
		}
	}
	if len(byTF) == 0 {
		return nil, fmt.Errorf("%w: no resources under %s", ErrSource, filepath.Base(dir))
	}
	out := make([]typemap.GenResource, 0, len(byTF))
	for _, tf := range slices.Sorted(maps.Keys(byTF)) {
		out = append(out, byTF[tf])
	}
	return out, nil
}

// merge adds r to byTF. A registration with an identity wins, and a list registration marks the
// type as listable with the list config's required attributes.
func merge(byTF map[string]typemap.GenResource, r typemap.GenResource, required []string) {
	cur, ok := byTF[r.TF]
	list := r.List || cur.List
	if !ok || (cur.Identity == "" && r.Identity != "") {
		cur = r
	}
	cur.List = list
	if list {
		cur.ListRequired = required
	}
	byTF[r.TF] = cur
}

// resourceFuncs are the generated methods that register resources. List resources repeat a
// resource's identity, so they fill in an identity the resource registration lacks.
func resourceFuncs() []string {
	return append([]string{"SDKResources", "FrameworkResources"}, listFuncs()...)
}

// listFuncs are the generated methods that register list resources.
func listFuncs() []string { return []string{"SDKListResources", "FrameworkListResources"} }

func servicePackage(path, service string, attrs map[string]string) ([]typemap.GenResource, error) {
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.SkipObjectResolution)
	if err != nil {
		return nil, fmt.Errorf("%w: parse %s: %w", ErrSource, service, err)
	}
	var out []typemap.GenResource
	var errs []error
	for _, decl := range f.Decls {
		fd, ok := decl.(*ast.FuncDecl)
		if !ok || fd.Recv == nil || !slices.Contains(resourceFuncs(), fd.Name.Name) {
			continue
		}
		list := slices.Contains(listFuncs(), fd.Name.Name)
		ast.Inspect(fd.Body, func(n ast.Node) bool {
			lit, isLit := n.(*ast.CompositeLit)
			if !isLit {
				return true
			}
			r, isResource, litErr := resourceLit(lit, service, attrs)
			if litErr != nil {
				errs = append(errs, fmt.Errorf("%s: %w", service, litErr))
			}
			if isResource {
				r.List = list
				out = append(out, r)
				return false
			}
			return true
		})
	}
	return out, errors.Join(errs...)
}

func resourceLit(lit *ast.CompositeLit, service string, attrs map[string]string) (typemap.GenResource, bool, error) {
	r := typemap.GenResource{Service: service}
	var identity *ast.CallExpr
	for _, elt := range lit.Elts {
		kv, ok := elt.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		key, isIdent := kv.Key.(*ast.Ident)
		if !isIdent {
			continue
		}
		switch key.Name {
		case "TypeName":
			r.TF, _ = stringLit(kv.Value)
		case "Region":
			if call, isCall := kv.Value.(*ast.CallExpr); isCall && funcName(call) == "ResourceRegionDisabled" {
				r.Global = true
			}
		case "Identity":
			identity, _ = kv.Value.(*ast.CallExpr)
		}
	}
	if r.TF == "" || !strings.HasPrefix(r.TF, "aws_") {
		return r, false, nil
	}
	if identity != nil {
		if err := setIdentity(&r, identity, attrs); err != nil {
			return r, true, fmt.Errorf("%s: %w", r.TF, err)
		}
	}
	return r, true, nil
}

func funcName(call *ast.CallExpr) string {
	switch fn := call.Fun.(type) {
	case *ast.SelectorExpr:
		return fn.Sel.Name
	case *ast.Ident:
		return fn.Name
	}
	return ""
}

// identityKinds maps the provider's identity constructors to the kind tfcensus records and the
// base attributes the constructor adds.
func identityKinds() map[string]struct {
	kind string
	base []string
} {
	regional := []string{typemap.IdentityAccountID, typemap.IdentityRegion}
	global := []string{typemap.IdentityAccountID}
	type k = struct {
		kind string
		base []string
	}
	return map[string]k{
		"RegionalSingleParameterIdentity":          {"regional-single-parameter", regional},
		"GlobalSingleParameterIdentity":            {"global-single-parameter", global},
		"RegionalParameterizedIdentity":            {"regional-parameterized", regional},
		"GlobalParameterizedIdentity":              {"global-parameterized", global},
		"RegionalARNIdentity":                      {"regional-arn", nil},
		"RegionalARNIdentityNamed":                 {"regional-arn", nil},
		"GlobalARNIdentity":                        {"global-arn", nil},
		"GlobalARNIdentityNamed":                   {"global-arn", nil},
		"RegionalResourceWithGlobalARNFormat":      {"regional-global-arn-format", []string{typemap.IdentityRegion}},
		"RegionalResourceWithGlobalARNFormatNamed": {"regional-global-arn-format", []string{typemap.IdentityRegion}},
		"RegionalSingletonIdentity":                {"regional-singleton", regional},
		"GlobalSingletonIdentity":                  {"global-singleton", global},
		"RegionalCustomInherentRegionIdentity":     {"regional-custom-inherent-region", nil},
	}
}

var errIdentity = errors.New("unknown identity")

func setIdentity(r *typemap.GenResource, call *ast.CallExpr, attrs map[string]string) error {
	name := funcName(call)
	k, ok := identityKinds()[name]
	if !ok {
		return fmt.Errorf("%w constructor %s", errIdentity, name)
	}
	r.Identity = k.kind
	r.IdentityAttrs = slices.Clone(k.base)
	switch {
	case strings.Contains(name, "ARN"):
		attr := "arn"
		if strings.HasSuffix(name, "Named") && len(call.Args) > 0 {
			attr = resolveName(call.Args[0], attrs)
		}
		r.IdentityAttrs = append(r.IdentityAttrs, attr)
	case strings.Contains(name, "CustomInherentRegion"):
		if len(call.Args) > 0 {
			r.IdentityAttrs = append(r.IdentityAttrs, resolveName(call.Args[0], attrs))
		}
	default:
		for _, p := range identityParams(name, call) {
			if err := addIdentityAttr(r, p, attrs); err != nil {
				return fmt.Errorf("%w in %s", err, name)
			}
		}
	}
	return nil
}

// identityParams returns the attribute expressions of a single-parameter or parameterized
// identity constructor.
func identityParams(name string, call *ast.CallExpr) []ast.Expr {
	if len(call.Args) == 0 {
		return nil
	}
	if strings.Contains(name, "SingleParameter") {
		return call.Args[:1]
	}
	if cl, isLit := call.Args[0].(*ast.CompositeLit); isLit && strings.Contains(name, "Parameterized") {
		return cl.Elts
	}
	return nil
}

// addIdentityAttr reads one StringIdentityAttribute(name, required[, mappedName]) call.
func addIdentityAttr(r *typemap.GenResource, p ast.Expr, attrs map[string]string) error {
	pc, ok := p.(*ast.CallExpr)
	if !ok || len(pc.Args) == 0 {
		return fmt.Errorf("%w attribute", errIdentity)
	}
	attr := resolveName(pc.Args[0], attrs)
	if attr == unresolved {
		return fmt.Errorf("%w attribute name", errIdentity)
	}
	r.IdentityAttrs = append(r.IdentityAttrs, attr)
	if len(pc.Args) > 1 {
		if b, isIdent := pc.Args[1].(*ast.Ident); isIdent && b.Name == "false" {
			r.IdentityOptional = append(r.IdentityOptional, attr)
		}
	}
	const mappedArg = 2
	if strings.HasSuffix(funcName(pc), "WithMappedName") && len(pc.Args) > mappedArg {
		if r.IdentityFrom == nil {
			r.IdentityFrom = map[string]string{}
		}
		r.IdentityFrom[attr] = resolveName(pc.Args[mappedArg], attrs)
	}
	return nil
}

func resolveName(e ast.Expr, attrs map[string]string) string {
	if s, ok := stringLit(e); ok {
		return s
	}
	if id, ok := e.(*ast.Ident); ok {
		if v, known := attrs[id.Name]; known {
			return v
		}
		return unresolved
	}
	sel, ok := e.(*ast.SelectorExpr)
	if !ok {
		return unresolved
	}
	if pkg, isIdent := sel.X.(*ast.Ident); isIdent {
		if v, known := attrs[pkg.Name+"."+sel.Sel.Name]; known {
			return v
		}
	}
	return unresolved
}

// unresolved stands for a name that is neither a string literal nor a known names.AttrX.
const unresolved = "?"

// tagTypes reads the tag policy mapping from tagging types (which Resource Explorer shares) to TF
// types, and returns the tagging types of each TF type.
func tagTypes(path string) (map[string][]string, error) {
	body, err := hclBody(path)
	if err != nil {
		return nil, err
	}
	out := map[string][]string{}
	for _, b := range body.Blocks {
		if b.Type != "tagtype" || len(b.Labels) != 1 {
			continue
		}
		attr, ok := b.Body.Attributes["terraform_types"]
		if !ok {
			continue
		}
		v, diags := attr.Expr.Value(nil)
		if diags.HasErrors() {
			return nil, fmt.Errorf("%w: %s: %s", ErrSource, filepath.Base(path), diags.Error())
		}
		for it := v.ElementIterator(); it.Next(); {
			_, tf := it.Element()
			out[tf.AsString()] = append(out[tf.AsString()], b.Labels[0])
		}
	}
	for tf := range out {
		slices.Sort(out[tf])
	}
	return out, nil
}

// cfnTypes reads awscc's resource schemas: awscc type name (without the awscc prefix) to
// CloudFormation type.
func cfnTypes(path string) (map[string]string, error) {
	body, err := hclBody(path)
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	for _, b := range body.Blocks {
		if b.Type != "resource_schema" || len(b.Labels) != 1 {
			continue
		}
		attr, ok := b.Body.Attributes["cloudformation_type_name"]
		if !ok {
			continue
		}
		v, diags := attr.Expr.Value(nil)
		if diags.HasErrors() {
			return nil, fmt.Errorf("%w: %s: %s", ErrSource, filepath.Base(path), diags.Error())
		}
		out[b.Labels[0]] = v.AsString()
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("%w: no resource schemas in %s", ErrSource, filepath.Base(path))
	}
	return out, nil
}

func hclBody(path string) (*hclsyntax.Body, error) {
	src, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("%w: %w", ErrSource, err)
	}
	f, diags := hclsyntax.ParseConfig(src, filepath.Base(path), hcl.InitialPos)
	if diags.HasErrors() {
		return nil, fmt.Errorf("%w: %s", ErrSource, diags.Error())
	}
	body, ok := f.Body.(*hclsyntax.Body)
	if !ok {
		return nil, fmt.Errorf("%w: %s is not native HCL", ErrSource, filepath.Base(path))
	}
	return body, nil
}

// guessCFN returns the CloudFormation type whose awscc name equals the TF type, either as is or
// with the service name inserted (aws_vpc in package ec2 is awscc's aws_ec2_vpc).
func guessCFN(r *typemap.GenResource, cfn map[string]string) string {
	if c, ok := cfn[r.TF]; ok {
		return c
	}
	rest := strings.TrimPrefix(r.TF, "aws_")
	if strings.HasPrefix(rest, r.Service+"_") {
		return ""
	}
	return cfn["aws_"+r.Service+"_"+rest]
}

// licenseFile writes the MPL-2.0 text once, after a header naming both copyright holders. The
// two LICENSE files differ only in their first line.
func licenseFile(awsDir, awsccDir string, awsSrc, ccSrc typemap.Source) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("generated.yaml is derived from the following MPL-2.0 sources:\n\n")
	var text string
	for _, s := range []struct {
		dir string
		src typemap.Source
	}{{awsDir, awsSrc}, {awsccDir, ccSrc}} {
		raw, err := os.ReadFile(filepath.Join(s.dir, "LICENSE"))
		if err != nil {
			return nil, fmt.Errorf("%w: %s: %w", ErrSource, s.src.Repo, err)
		}
		first, rest, _ := strings.Cut(string(raw), "\n")
		fmt.Fprintf(&b, "- https://github.com/%s at %s\n  %s\n", s.src.Repo, s.src.Commit, strings.TrimSpace(first))
		if text == "" {
			text = rest
		} else if rest != text {
			return nil, fmt.Errorf("%w: the two LICENSE texts differ beyond their first line", ErrSource)
		}
	}
	b.WriteString("\n")
	sc := bufio.NewScanner(strings.NewReader(strings.TrimLeft(text, "\n")))
	for sc.Scan() {
		b.WriteString(strings.TrimRight(sc.Text(), " \t") + "\n")
	}
	return b.Bytes(), nil
}

const acct = "111111111111"

// date is 2026-11-13 in UTC, so the file names show the clock is read in UTC.
func date() time.Time { return time.Date(2026, 11, 12, 23, 30, 0, 0, time.FixedZone("x", -3600)) }

func loadMap(t *testing.T) *typemap.Map {
	t.Helper()
	m, err := typemap.Load()
	require.NoError(t, err)
	return m
}

func role(name, nameTag string) scan.Finding {
	f := scan.Finding{
		Account: acct, Category: scan.CategoryUnmanaged, CFNType: "AWS::IAM::Role",
		TFTypes: []string{"aws_iam_role"}, ARN: "arn:aws:iam::" + acct + ":role/" + name, ID: name, Name: name,
		Reason: "no state manages it and no rule matches", Rule: ownership.RuleNoMatch,
	}
	if nameTag != "" {
		f.Tags = map[string]string{"Name": nameTag}
	}
	return f
}

func findings() []scan.Finding {
	return []scan.Finding{
		role("admin-role", ""),
		role("ops", "Admin Role"),
		role("2fa-checker", ""),
		{
			Account: acct, Region: "eu-west-1", Category: scan.CategoryUnmanaged, CFNType: "AWS::EC2::SecurityGroup",
			TFTypes: []string{"aws_security_group"},
			ARN:     "arn:aws:ec2:eu-west-1:" + acct + ":security-group/sg-0c11c0b5000000003",
			ID:      "sg-0c11c0b5000000003", Name: "clickops-debug", Tags: map[string]string{"owner": "alice"},
		},
		{
			Account: acct, Category: scan.CategoryManaged, CFNType: "AWS::IAM::Role", TFTypes: []string{"aws_iam_role"},
			ARN: "arn:aws:iam::" + acct + ":role/managed", Name: "managed",
		},
		{
			Account: acct, Region: "eu-west-1", Category: scan.CategoryUnmanaged, CFNType: "AWS::EC2::KeyPair",
			ID: "key-1",
		},
	}
}

func target(t *testing.T, s string) codify.Target {
	t.Helper()
	tg, err := codify.ParseTarget(s)
	require.NoError(t, err)
	return tg
}

func generate(t *testing.T, fs []scan.Finding, o codify.Options) *codify.Result {
	t.Helper()
	if o.Map == nil {
		o.Map = loadMap(t)
	}
	o.From, o.Date = "scan.json", date()
	res, err := codify.Generate(fs, o)
	require.NoError(t, err)
	return res
}

func parse(t *testing.T, f codify.File) *hcl.File {
	t.Helper()
	file, diags := hclparse.NewParser().ParseHCL(f.Content, f.Name)
	require.False(t, diags.HasErrors(), "%s: %s\n%s", f.Name, diags.Error(), f.Content)
	return file
}

// TestSpec_whois_and_codify_2: codify output is valid HCL, the same input gives the same bytes in
// any order, and colliding names get numeric suffixes in a stable order.
func TestSpec_whois_and_codify_2(t *testing.T) {
	t.Parallel()

	o := codify.Options{Target: target(t, "terraform@1.12.2")}
	first := generate(t, findings(), o)
	reversed := findings()
	slices.Reverse(reversed)
	second := generate(t, reversed, o)
	require.Len(t, first.Files, 1)
	assert.Equal(t, "imports_tfcensus_20261113.tf", first.Files[0].Name, "the date is UTC")
	assert.Equal(t, string(first.Files[0].Content), string(second.Files[0].Content))
	parse(t, first.Files[0])

	want := `# Generated by tfcensus codify from scan.json. A starting point: review every block before you plan.
# Target: terraform 1.12.2.

import {
  # arn:aws:iam::111111111111:role/admin-role
  to = aws_iam_role.admin_role
  identity = {
    account_id = "111111111111"
    name       = "admin-role"
  }
}

import {
  # arn:aws:iam::111111111111:role/ops
  to = aws_iam_role.admin_role_2
  identity = {
    account_id = "111111111111"
    name       = "ops"
  }
}

import {
  # arn:aws:iam::111111111111:role/2fa-checker
  to = aws_iam_role.r_2fa_checker
  identity = {
    account_id = "111111111111"
    name       = "2fa-checker"
  }
}

import {
  # arn:aws:ec2:eu-west-1:111111111111:security-group/sg-0c11c0b5000000003
  to = aws_security_group.clickops_debug
  identity = {
    account_id = "111111111111"
    id         = "sg-0c11c0b5000000003"
    region     = "eu-west-1"
  }
}
`
	assert.Equal(t, want, string(first.Files[0].Content))
	assert.Equal(t, 5, first.Selected, "managed findings are not selected")
	require.Len(t, first.Skipped, 1)
	assert.Equal(t, "key-1", first.Skipped[0].Key)
	assert.Contains(t, first.Skipped[0].Reason, "no TF type maps to AWS::EC2::KeyPair")
}

// TestSpec_whois_and_codify_3: identity or id per target: TF 1.11 and OpenTofu 1.11 get id,
// TF 1.12+ and OpenTofu 1.12+ get identity, an aws provider before 6.0 gets id.
func TestSpec_whois_and_codify_3(t *testing.T) {
	t.Parallel()

	old := version.Must(version.NewVersion("5.100.0"))
	newer := version.Must(version.NewVersion("6.10.0"))
	for _, tc := range []struct {
		target   string
		provider *version.Version
		byID     bool
		want     string
		note     string
	}{
		{target: "terraform@1.11.4", want: codify.ByID, note: "has no import identity"},
		{target: "terraform@1.12.0", want: codify.ByIdentity},
		{target: "terraform@1.17.2", provider: newer, want: codify.ByIdentity, note: "unknown identity type"},
		{target: "opentofu@1.11.6", want: codify.ByID, note: "has no import identity"},
		{target: "opentofu@1.12.0", want: codify.ByIdentity},
		{target: "terraform@1.12.0", provider: old, want: codify.ByID, note: "has no resource identity"},
		{target: "terraform@1.12.0", byID: true, want: codify.ByID, note: "--import-by id"},
	} {
		t.Run(tc.target, func(t *testing.T) {
			t.Parallel()
			tg := target(t, tc.target)
			tg.Provider = tc.provider
			res := generate(t, []scan.Finding{role("app", "")}, codify.Options{Target: tg, ImportByID: tc.byID})
			require.Len(t, res.Imports, 1)
			imp := res.Imports[0]
			assert.Equal(t, tc.want, imp.By)
			if tc.want == codify.ByID {
				assert.Equal(t, "app", imp.ID)
				assert.Contains(t, string(res.Files[0].Content), `id = "app"`)
			} else {
				assert.Equal(t, map[string]string{"account_id": acct, "name": "app"}, imp.Identity)
			}
			if tc.note == "" {
				assert.Empty(t, res.Notes)
			} else {
				require.NotEmpty(t, res.Notes)
				assert.Contains(t, res.Notes[0], tc.note)
			}
			parse(t, res.Files[0])
		})
	}
}

func TestExistingNamesAndImports(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	src := `resource "aws_iam_role" "admin_role" {}

import {
  to = aws_iam_role.legacy
  identity = {
    name = "ops"
  }
}

import {
  to = module.x.aws_iam_role.admin_role_2
  id = "elsewhere"
}
`
	require.NoError(t, os.WriteFile(filepath.Join(dir, "main.tf"), []byte(src), 0o600))
	ex, err := codify.ReadExisting(dir)
	require.NoError(t, err)
	res := generate(t, findings()[:3], codify.Options{Target: target(t, "terraform@1.12.2"), Existing: ex})
	var addrs []string
	for _, imp := range res.Imports {
		addrs = append(addrs, imp.Address)
	}
	assert.Equal(t, []string{"aws_iam_role.admin_role_2", "aws_iam_role.r_2fa_checker"}, addrs)
	require.Len(t, res.Skipped, 1)
	assert.Equal(t, "already imported in main.tf", res.Skipped[0].Reason)
}

func TestSelectAndTypes(t *testing.T) {
	t.Parallel()

	sel, err := ownership.NewSelector(`resource.type == "AWS::EC2::SecurityGroup" && resource.tags["owner"] == "alice"`)
	require.NoError(t, err)
	res := generate(t, findings(), codify.Options{Target: target(t, "terraform@1.12.2"), Select: sel})
	require.Len(t, res.Imports, 1)
	assert.Equal(t, "aws_security_group.clickops_debug", res.Imports[0].Address)

	res = generate(
		t,
		findings(),
		codify.Options{Target: target(t, "terraform@1.12.2"), Types: scan.TypeMatcher{"aws_iam_*"}},
	)
	assert.Len(t, res.Imports, 3)

	_, err = ownership.NewSelector(`resource.nope`)
	require.ErrorIs(t, err, ownership.ErrRule)
}

func TestQueryFile(t *testing.T) {
	t.Parallel()

	res := generate(t, findings(), codify.Options{Target: target(t, "terraform@1.14.0"), Query: true})
	require.Len(t, res.Files, 2)
	q := res.Files[1]
	assert.Equal(t, "query_tfcensus_20261113.tfquery.hcl", q.Name)
	parse(t, q)
	want := `# Generated by tfcensus codify from scan.json. Each block lists every resource of its type, managed or not.

list "aws_iam_role" "tfcensus_global" {
  provider         = aws
  include_resource = true
}

list "aws_security_group" "tfcensus_eu_west_1" {
  provider         = aws
  include_resource = true

  config {
    region = "eu-west-1"
  }
}
`
	assert.Equal(t, want, string(q.Content))

	for _, tg := range []string{"terraform@1.13.5", "opentofu@1.13.9"} {
		res = generate(t, findings(), codify.Options{Target: target(t, tg), Query: true})
		assert.Len(t, res.Files, 1, tg)
		assert.Contains(t, res.Notes[len(res.Notes)-1], "no query file written", tg)
	}
}

func TestWriteRefusesOverwrite(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	files := []codify.File{{Name: "imports_tfcensus_20261112.tf", Content: []byte("# x\n")}}
	require.NoError(t, codify.Write(dir, files, false))
	require.ErrorIs(t, codify.Write(dir, files, false), codify.ErrExists)
	files[0].Content = []byte("# y\n")
	require.NoError(t, codify.Write(dir, files, true))
	b, err := os.ReadFile(filepath.Join(dir, files[0].Name))
	require.NoError(t, err)
	assert.Equal(t, "# y\n", string(b))
	require.Error(t, codify.Write(dir, []codify.File{{Name: "../escape.tf"}}, true))
	require.Error(t, codify.Write(filepath.Join(dir, "missing"), files, true))
	entries, err := os.ReadDir(dir)
	require.NoError(t, err)
	assert.Len(t, entries, 1, "no temp files left behind")
}

func TestSlug(t *testing.T) {
	t.Parallel()

	for in, want := range map[string]string{
		"Admin Role":            "admin_role",
		"my-bucket.example.com": "my_bucket_example_com",
		"2fa":                   "r_2fa",
		"__x__":                 "x",
		"Ünïcode":               "n_code",
		"":                      "resource",
		"---":                   "resource",
		string(make([]byte, 0)) + "a" + string(slices.Repeat([]byte("b"), 80)): "a" + string(slices.Repeat([]byte("b"), 63)),
	} {
		assert.Equal(t, want, codify.Slug(in), in)
	}
}

func TestParseTarget(t *testing.T) {
	t.Parallel()

	for _, bad := range []string{"terraform", "pulumi@1.0", "terraform@x"} {
		_, err := codify.ParseTarget(bad)
		require.ErrorIs(t, err, codify.ErrTarget, bad)
	}
	tg := target(t, "tofu@1.12.0-beta1")
	assert.Equal(t, codify.EngineOpenTofu, tg.Engine)
	assert.True(t, tg.IdentityEngine(), "a 1.12 prerelease has identity")
}

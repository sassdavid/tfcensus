package main

import (
	"fmt"
	"regexp"
	"strings"
)

// Table headers and flag names that several pages use.
const (
	colCommand     = "Command"
	colDescription = "Description"
	colType        = "Type"
	helpFlag       = "help"
	trueValue      = "true"
)

// generatedNote is the comment line in the frontmatter of every page gendocs writes.
const generatedNote = "# Generated by scripts/gendocs. Do not edit; run mise run docs."

// frontmatter returns the YAML frontmatter of a generated page.
func frontmatter(title, description string) string {
	return fmt.Sprintf("---\n%s\ntitle: %s\ndescription: %s\neditLink: false\n---\n\n",
		generatedNote, yamlString(title), yamlString(description))
}

func yamlString(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

var headingLine = regexp.MustCompile(`^#{1,6}\s+(.+?)\s*$`)

// prose turns help text into Markdown. Paragraphs with an indented line become fenced text
// blocks, so tables and commands keep their shape. Elsewhere, Markdown and HTML syntax is
// escaped, and "#### Name:" lines from cobra's completion help become bold paragraphs.
func prose(text string) string {
	text = strings.ReplaceAll(strings.TrimSpace(text), "\r\n", "\n")
	if text == "" {
		return ""
	}
	var out []string
	var block []string // lines of the current fenced block
	for para := range strings.SplitSeq(text, "\n\n") {
		lines := strings.Split(para, "\n")
		if hasIndented(lines) {
			if len(block) > 0 {
				block = append(block, "")
			}
			block = append(block, lines...)
			continue
		}
		out = append(out, fence(block)...)
		block = nil
		out = append(out, paragraph(lines)...)
	}
	out = append(out, fence(block)...)
	return strings.Join(out, "\n\n")
}

// fence returns lines as one fenced text block, or nothing when there are none.
func fence(lines []string) []string {
	for len(lines) > 0 && strings.TrimSpace(lines[len(lines)-1]) == "" {
		lines = lines[:len(lines)-1]
	}
	if len(lines) == 0 {
		return nil
	}
	return []string{"```text\n" + strings.Join(dedent(lines), "\n") + "\n```"}
}

// paragraph escapes the lines of one paragraph, and turns heading lines into bold paragraphs.
func paragraph(lines []string) []string {
	var out, ps []string
	for _, l := range lines {
		m := headingLine.FindStringSubmatch(l)
		if m == nil {
			ps = append(ps, inline(l))
			continue
		}
		if len(ps) > 0 {
			out = append(out, strings.Join(ps, "\n"))
			ps = nil
		}
		out = append(out, "**"+inline(strings.TrimSuffix(m[1], ":"))+"**")
	}
	if len(ps) > 0 {
		out = append(out, strings.Join(ps, "\n"))
	}
	return out
}

func hasIndented(lines []string) bool {
	for _, l := range lines {
		if strings.HasPrefix(l, "  ") || strings.HasPrefix(l, "\t") {
			return true
		}
	}
	return false
}

// dedent removes the indentation that all non-blank lines share and turns tabs into two spaces.
func dedent(lines []string) []string {
	out := make([]string, len(lines))
	minIndent := -1
	for i, l := range lines {
		l = strings.ReplaceAll(l, "\t", "  ")
		out[i] = strings.TrimRight(l, " ")
		if strings.TrimSpace(l) == "" {
			continue
		}
		n := len(l) - len(strings.TrimLeft(l, " "))
		if minIndent < 0 || n < minIndent {
			minIndent = n
		}
	}
	for i, l := range out {
		if len(l) >= minIndent && minIndent > 0 {
			out[i] = l[minIndent:]
		}
	}
	return out
}

// inline escapes one line of help text for VitePress outside code spans: HTML and Vue syntax,
// emphasis markers and a leading block marker.
func inline(s string) string {
	var b strings.Builder
	parts := strings.Split(s, "`")
	for i, p := range parts {
		if i%2 == 1 && i < len(parts)-1 {
			b.WriteString("`" + p + "`")
			continue
		}
		if i%2 == 1 {
			b.WriteString("`")
		}
		b.WriteString(escapeText(p))
	}
	out := b.String()
	if t := strings.TrimLeft(out, " "); t != "" && strings.ContainsAny(t[:1], "#>+-=") && !strings.HasPrefix(t, "--") {
		out = `\` + t
	}
	return out
}

func escapeText(s string) string {
	return strings.NewReplacer(
		"<", "&lt;",
		">", "&gt;",
		"*", `\*`,
		"_", `\_`,
		"[", `\[`,
		"]", `\]`,
		"|", `\|`,
		"{{", "<span v-pre>{{</span>",
		"}}", "<span v-pre>}}</span>",
	).Replace(s)
}

// cell formats text for one table cell.
func cell(s string) string {
	return inline(strings.Join(strings.Fields(s), " "))
}

// code formats s as an inline code span.
func code(s string) string {
	if strings.Contains(s, "`") {
		return "`` " + s + " ``"
	}
	return "`" + strings.ReplaceAll(s, "|", `\|`) + "`"
}

// table returns a Markdown table.
func table(header []string, rows [][]string) string {
	var b strings.Builder
	b.WriteString("| " + strings.Join(header, " | ") + " |\n|")
	for range header {
		b.WriteString("---|")
	}
	b.WriteString("\n")
	for _, r := range rows {
		b.WriteString("| " + strings.Join(r, " | ") + " |\n")
	}
	return b.String()
}

package main

import (
	"fmt"
	"regexp"
	"strings"
)

// generatedNote is the comment line in the frontmatter of every page gensite writes.
const generatedNote = "# Generated by scripts/gensite. Do not edit; run mise run docs."

// partNote opens every Markdown part gensite writes for a hand-written page to include.
const partNote = "<!-- Generated by scripts/gensite. Do not edit; run mise run docs. -->\n\n"

// frontmatter returns the YAML frontmatter of a generated page.
func frontmatter(title, description string) string {
	return fmt.Sprintf("---\n%s\ntitle: %s\ndescription: %s\neditLink: false\n---\n\n",
		generatedNote, yamlString(title), yamlString(description))
}

func yamlString(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

// cell escapes text for a Markdown table cell that VitePress compiles as a Vue template.
func cell(s string) string {
	return strings.NewReplacer("|", `\|`, "*", `\*`, "<", "&lt;", ">", "&gt;", "\n", " ").Replace(s)
}

// code returns s as inline code for a table cell.
func code(s string) string {
	if s == "" {
		return ""
	}
	return "`" + strings.NewReplacer("|", `\|`, "\n", " ").Replace(s) + "`"
}

// codeList returns each value as inline code, joined by commas.
func codeList(vs []string) string {
	out := make([]string, len(vs))
	for i, v := range vs {
		out[i] = code(v)
	}
	return strings.Join(out, ", ")
}

// fenced returns s as a fenced block in lang. The fence is longer than any backtick run in s.
func fenced(lang, s string) string {
	fence := "```"
	for strings.Contains(s, fence) {
		fence += "`"
	}
	return fence + lang + "\n" + strings.TrimRight(s, "\n") + "\n" + fence + "\n"
}

var slugSep = regexp.MustCompile(`[^a-z0-9]+`)

// slug returns the anchor VitePress gives a heading of plain text.
func slug(s string) string {
	return strings.Trim(slugSep.ReplaceAllString(strings.ToLower(s), "-"), "-")
}

// table writes a Markdown table with header and rows, whose cells are already escaped.
func table(b *strings.Builder, header []string, rows [][]string) {
	b.WriteString("| " + strings.Join(header, " | ") + " |\n|")
	for range header {
		b.WriteString("---|")
	}
	b.WriteString("\n")
	for _, r := range rows {
		b.WriteString("| " + strings.Join(r, " | ") + " |\n")
	}
	b.WriteString("\n")
}
